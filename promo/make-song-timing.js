// Builds promo/song-timing.js from the Oh Hell music script, so the promo knows when every
// sung syllable of "God Rest Ye Merry Starmen (In Her Own Words)" falls.
// Run: node promo/make-song-timing.js "D:/CodeGen/Oh Hell/oh-music.js"
'use strict';
const fs=require('fs'),path=require('path');
const src=process.argv[2]||'D:/CodeGen/Oh Hell/oh-music.js';
global.window=global;eval(fs.readFileSync(src,'utf8'));
const L=global.OHMusicLib,T=L.TUNES.find(t=>t.id==='xmasWords');
const beat=60/T.bpm,bar=beat*T.beats,start=0;   // the renders/ WAV (tools/render-wav.js) starts on the first bar
const at=(b,x=0)=>+(start+b*bar+x*beat).toFixed(4);
const sections=T.sections.map(([b,name])=>({name,bar:b,t:at(b)}));
const sec=b=>{let s=T.sections[0];for(const x of T.sections)if(x[0]<=b)s=x;return{name:s[1],k:b-s[0]}};
const notes=[];
T.lead.forEach((events,b)=>{const {name,k}=sec(b);
  const crowd=(name==='verse 3'&&k>=12)||name==='outro';
  const harmony=name==='outro'||(name.startsWith('verse')&&k>=11);
  for(const e of events||[])notes.push({t:at(b,e.at),d:+(e.beats*beat).toFixed(4),syl:e.syl||'',stress:!!e.stress,midi:e.midi,crowd,harmony:harmony&&!e.part})});
// The breakdown's legato line (the aria), sung once from the first breakdown bar.
const BREAK='E5:1:o:scoop B5:2:-:slide A5:1 | G5:1 F#5:1 E5:1 D5:1 | g:D5 E5:1:shi F#5:1 G5:1 A5:1:-:slide | B5:3.5:-:tr r:0.5 | '+
  'E5:1:mo:scoop B5:2:-:slide A5:1 | G5:1:-:turn F#5:1 E5:1 D5:1 | E5:1 F#5:1 G5:1 A5:1 | G#5:2.5:-:fall r:1.5';
const aria=[];let pos=0;const b0=T.sections.find(s=>s[1]==='breakdown')[0];
for(const tok of BREAK.split(/\s+/)){if(!tok||tok==='|')continue;const p=tok.split(':');if(p[0]==='g')continue;
  if(p[0]==='r'){pos+=+p[1];continue}aria.push({t:at(b0,pos),d:+(+p[1]*beat).toFixed(4),syl:p[2]&&p[2]!=='-'?p[2]:'',midi:L.midiOf(p[0]),legato:true,...(p[3]?{fl:p[3]}:{})});pos+=+p[1]}
const out={title:T.title,bpm:T.bpm,beat,bar,start,bars:T.chords.length,end:at(T.chords.length),sections,notes,aria};
fs.writeFileSync(path.join(__dirname,'song-timing.js'),'// Generated by make-song-timing.js from the Oh Hell music script. Do not edit by hand.\nwindow.PROMO_SONG='+JSON.stringify(out)+';\n');
console.log(sections.map(s=>s.name+' '+s.t.toFixed(2)).join(' | '),'\nnotes',notes.length,'aria',aria.length,'end',out.end);
